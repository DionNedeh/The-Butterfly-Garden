/** An image the manifest names, relative to the manifest's own address. */
interface ManifestImage {
  src: string
  sizes: string
  type: string
  purpose?: 'any' | 'maskable'
}

/**
 * The parts of a web app manifest this app uses. Declared here rather than
 * imported from vite-plugin-pwa, whose types bring Node's along with them and
 * would change what `setTimeout` means everywhere else in the app's code.
 * vite.config.ts hands it to the plugin, which checks that it fits.
 */
interface WebAppManifest {
  id: string
  name: string
  short_name: string
  description: string
  categories: string[]
  theme_color: string
  background_color: string
  display: 'standalone'
  start_url: string
  scope: string
  icons: ManifestImage[]
  shortcuts: { name: string; description: string; url: string; icons: ManifestImage[] }[]
  screenshots: (ManifestImage & { form_factor: 'narrow' | 'wide'; label: string })[]
}

/**
 * The web app manifest: how the PWA presents itself when it is installed.
 *
 * Kept apart from vite.config.ts so a test can check it against the files in
 * public/ and the app's own routes. Only the PWA has one; the Android app is
 * installed from Google Play and its store listing does this job there.
 *
 * Every relative `src` resolves against the manifest's own address, which is
 * the base path, so the files are named as they sit in public/. URLs in
 * shortcuts are written out in full from `base` instead, since a bare `#/…`
 * would resolve against the manifest file rather than the app.
 */
export function pwaManifest(base: string): WebAppManifest {
  return {
    // The address browsers already used as this app's identity before it
    // was written down (the start URL), so an installed copy stays the same
    // app rather than becoming a second one.
    id: base,
    name: 'The Butterfly Garden',
    short_name: 'Butterfly Garden',
    description: 'A private, gentle self-care garden that grows with you.',
    categories: ['health', 'lifestyle'],
    theme_color: '#315c4b',
    background_color: '#f8f2df',
    display: 'standalone',
    start_url: base,
    scope: base,
    icons: [
      {
        src: 'icons/icon-192.webp',
        sizes: '192x192',
        type: 'image/webp',
        purpose: 'any',
      },
      {
        // The artwork as drawn, never cropped: it runs almost to its edges.
        src: 'icons/icon-512.webp',
        sizes: '512x512',
        type: 'image/webp',
        purpose: 'any',
      },
      {
        // The same artwork inside the central safe zone, on paper to every
        // edge, for launchers that cut icons to a circle or a squircle.
        // Generated by scripts/generate-android-icons.py.
        src: 'icons/icon-maskable-512.webp',
        sizes: '512x512',
        type: 'image/webp',
        purpose: 'maskable',
      },
      {
        // PNG fallback for installers that will not take a WebP icon.
        src: 'icons/apple-touch-icon.png',
        sizes: '180x180',
        type: 'image/png',
        purpose: 'any',
      },
    ],
    // A long press on the installed icon. Each opens a page lib/routes knows.
    shortcuts: [
      {
        name: 'Check in',
        description: 'Note your inner weather for today',
        url: `${base}#/today/check-in`,
        icons: [{ src: 'icons/shortcut-check-in.png', sizes: '192x192', type: 'image/png' }],
      },
      {
        name: 'Today',
        description: 'Your goals and reflection for today',
        url: `${base}#/today`,
        icons: [{ src: 'icons/shortcut-today.png', sizes: '192x192', type: 'image/png' }],
      },
      {
        name: 'Journal',
        description: 'Everything you have written',
        url: `${base}#/journal`,
        icons: [{ src: 'icons/shortcut-journal.png', sizes: '192x192', type: 'image/png' }],
      },
    ],
    // Shown in the richer install sheet. Captured from the app itself (see
    // scripts/pwa-screenshots.mjs) and left out of the offline precache:
    // only the install sheet ever asks for them.
    screenshots: [
      {
        src: 'screenshots/garden-narrow.png',
        sizes: '780x1688',
        type: 'image/png',
        form_factor: 'narrow',
        label: 'Your garden: plants in bloom and butterflies you have welcomed',
      },
      {
        src: 'screenshots/today-narrow.png',
        sizes: '780x1688',
        type: 'image/png',
        form_factor: 'narrow',
        label: 'Today: a gentle check-in and a few small goals',
      },
      {
        src: 'screenshots/garden-wide.png',
        sizes: '1280x800',
        type: 'image/png',
        form_factor: 'wide',
        label: 'The garden on a larger screen',
      },
    ],
  }
}
